run_g1() {
  exec "${SCRIPT_DIR}/g1/run_g1_policy_sim.sh" "$@"
}

run_bumi_real() {
  printf '\nBUMI RGMT 真机端:\n'
  printf '  1) x86 端：PICO -> UDP relay\n'
  printf '  2) BUMI 端：UDP -> GMR -> RGMT -> Noetix\n'
  printf '  q) 返回\n'
  read -r -p '请选择 [1-2/q]: ' choice
  case "${choice}" in
    1)
      configure_x86_relay || return 1
      exec "${SCRIPT_DIR}/relay/run_xrobot_frame_relay.sh" "$@"
      ;;
    2)
      configure_bumi_udp || return 1
      KITOV_BUMI_BODY_SOURCE=udp exec "${SCRIPT_DIR}/bumi/run_bumi_policy_real.sh" "$@"
      ;;
    q|Q) return 0 ;;
    *) echo '无效选择' >&2; return 1 ;;
  esac
}

run_bumi() {
  printf '\nBUMI 模式:\n'
  printf '  1) BFM policy MuJoCo 仿真\n'
  printf '  2) RGMT MuJoCo 仿真\n'
  printf '  3) RGMT 真机\n'
  printf '  q) 返回\n'
  read -r -p '请选择 [1-3/q]: ' choice
  case "${choice}" in
    1) exec "${SCRIPT_DIR}/bumi/run_bumi_policy_sim.sh" "$@" ;;
    2) exec "${SCRIPT_DIR}/bumi/run_bumi_rgmt_policy_sim.sh" "$@" ;;
    3) run_bumi_real "$@" ;;
    q|Q) return 0 ;;
    *) echo '无效选择' >&2; return 1 ;;
  esac
}

run_openarm() {
  exec "${SCRIPT_DIR}/openarm/run_openarm_teleop.sh" "$@"
}

if [[ "$#" -gt 0 ]]; then
  case "$1" in
    g1) shift; run_g1 "$@" ;;
    bumi) shift; run_bumi "$@" ;;
    openarm) shift; run_openarm "$@" ;;
    *)
      echo "用法: $0 [g1|bumi|openarm] [额外参数...]" >&2
      exit 2
      ;;
  esac
fi

while true; do
  printf '\nKitov 启动器\n'
  printf '  1) G1 policy MuJoCo 仿真\n'
  printf '  2) BUMI\n'
  printf '  3) OpenArm v1 实时遥操作\n'
  printf '  q) 退出\n'
  read -r -p '请选择 [1-3/q]: ' choice
  case "${choice}" in
    1) run_g1 ;;
    2) run_bumi ;;
    3) run_openarm ;;
    q|Q) exit 0 ;;
    *) echo '无效选择' >&2 ;;
  esac
done
