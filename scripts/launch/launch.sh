#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"

save_relay_config() {
  local config_file="$1"
  local target_host="$2"
  local target_port="$3"
  local source_host="$4"
  local body_port="$5"
  mkdir -p "$(dirname -- "${config_file}")"
  {
    printf 'KITOV_XROBOT_RELAY_TARGET_HOST=%q\n' "${target_host}"
    printf 'KITOV_XROBOT_RELAY_TARGET_PORT=%q\n' "${target_port}"
    printf 'KITOV_BUMI_BODY_SOURCE_HOST=%q\n' "${source_host}"
    printf 'KITOV_BUMI_BODY_PORT=%q\n' "${body_port}"
  } >"${config_file}"
}

configure_x86_relay() {
  local config_file="${KITOV_XROBOT_RELAY_CONFIG:-${REPO_ROOT}/workspace/xrobot_relay.env}"
  local env_target_host="${KITOV_XROBOT_RELAY_TARGET_HOST-}"
  local env_target_port="${KITOV_XROBOT_RELAY_TARGET_PORT-}"
  local env_source_host="${KITOV_BUMI_BODY_SOURCE_HOST-}"
  local env_body_port="${KITOV_BUMI_BODY_PORT-}"
  local target_host="192.168.110.83"
  local target_port="47001"
  local source_host="192.168.110.84"
  local body_port="47001"
  local input_host input_port

  if [[ -f "${config_file}" ]]; then
    # This file is generated by this menu and contains only shell assignments.
    # shellcheck disable=SC1090
    source "${config_file}"
    target_host="${KITOV_XROBOT_RELAY_TARGET_HOST:-${target_host}}"
    target_port="${KITOV_XROBOT_RELAY_TARGET_PORT:-${target_port}}"
    source_host="${KITOV_BUMI_BODY_SOURCE_HOST:-${source_host}}"
    body_port="${KITOV_BUMI_BODY_PORT:-${body_port}}"
  fi
  [[ -n "${env_target_host}" ]] && target_host="${env_target_host}"
  [[ -n "${env_target_port}" ]] && target_port="${env_target_port}"
  [[ -n "${env_source_host}" ]] && source_host="${env_source_host}"
  [[ -n "${env_body_port}" ]] && body_port="${env_body_port}"

  printf '\nPICO -> BUMI UDP relay 配置:\n'
  printf '默认目标 IP：%s\n' "${target_host}"
  read -r -p "目标 IP（直接回车确认）：" input_host
  if [[ -n "${input_host}" ]]; then
    target_host="${input_host}"
  fi

  printf '默认目标端口：%s\n' "${target_port}"
  read -r -p "目标端口（直接回车确认）：" input_port
  if [[ -n "${input_port}" ]]; then
    target_port="${input_port}"
  fi

  if [[ -z "${target_host}" ]]; then
    echo '目标 IP 不能为空' >&2
    return 1
  fi
  if [[ ! "${target_port}" =~ ^[0-9]+$ ]] || ((target_port < 1 || target_port > 65535)); then
    echo "目标端口无效：${target_port}，必须是 1-65535" >&2
    return 1
  fi

  save_relay_config "${config_file}" "${target_host}" "${target_port}" "${source_host}" "${body_port}"
  echo "已保存 relay 配置：${config_file}"

  KITOV_XROBOT_RELAY_TARGET_HOST="${target_host}"
  KITOV_XROBOT_RELAY_TARGET_PORT="${target_port}"
  export KITOV_XROBOT_RELAY_TARGET_HOST KITOV_XROBOT_RELAY_TARGET_PORT
}

